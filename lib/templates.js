/**
 * The EN|FR switcher.
 *
 * It links to the SAME page in the other language — the single most common
 * execution failure in bilingual sites is a switcher that dumps everyone on the
 * translated homepage, which trains people never to touch it again.
 *
 * RENDERED ONLY WHERE BOTH VERSIONS EXIST. A page with no French counterpart
 * shows no toggle at all, rather than a toggle that silently means "go to the
 * French homepage and find your own way back" — which is the same failure as
 * above wearing a different hat. Because TRANSLATED_PAGES is measured from actual
 * coverage, a page grows its toggle, in both languages at once, on the build
 * after its translation is finished.
 *
 * `hreflang`+`lang` on the anchor tell a screen reader to pronounce the label in
 * the target language, and tell a crawler what is on the other end of the link.
 *
 * The visible label is the two-letter code, not the language name. Partly it is
 * the convention, but concretely: "English" is 7 characters in a nav bar that has
 * to fit six French labels which are already ~20% longer than their English
 * counterparts, and the horizontal nav has to survive down to 1001px before the
 * burger takes over at 1000px. The full phrase lives in `title`/`aria-label`,
 * where it costs no width and still reaches a screen reader.
 *
 * Emitted in BOTH directions: French pages link back to English, and the English
 * pages that have a French twin advertise it. Without the English half, /fr is
 * reachable only by typing the URL or arriving from Google — the French site
 * exists but nobody browsing the English one can find it.
 */
export function localeSwitcherHtml(file, locale = DEFAULT_LOCALE) {
  if (!TRANSLATED_PAGES.has(file)) return '';
  const other = otherLocale(locale);
  const href = cleanPath(file, other);
  const label = esc(t(locale, 'switchLabel'));
  return `    <li class="nav-lang"><a href="${href}" hreflang="${other}" lang="${other}" title="${label}" aria-label="${label}" data-cursor>${t(locale, 'switchTo')}</a></li>\n`;
}

