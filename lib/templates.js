/**
 * The favicon block — ONE source of truth, emitted by every renderer that writes a
 * <head> (seoHtml here, blog-render, blog-404, composed-render, and the hand-written
 * /admin + /seoteam shells).
 *
 * Do NOT point these at LOGO. That file is 579x424 with a transparent background,
 * and both of those facts break it as an icon:
 *   - Google only renders a favicon in search results when it is SQUARE (it wants a
 *     multiple of 48px). A non-square icon is dropped and the generic globe is shown
 *     instead — which is what /reddit-ads-montreal and friends were getting.
 *   - A black mark on transparency vanishes in a dark browser tab.
 * The square, opaque set these tags reference is generated from LOGO by
 * `npm run favicon` (scripts/gen-favicon.js) and committed.
 *
 * /favicon.ico is also present at the web root because Google and every browser probe
 * that path directly when a page declares no icon at all (e.g. a raw 404 or an API
 * response), and it is the only icon path some SERP surfaces will look for.
 *
 * The `sizes` values are LOAD-BEARING METADATA, not decoration: a consumer picks which
 * icon to fetch from this attribute WITHOUT downloading any of them. Two consequences
 * this list is shaped around:
 *   - /favicon.ico is a multi-resolution container holding 16, 32 AND 48 (see ICO_SIZES
 *     in scripts/gen-favicon.js). Declaring only "32x32" hid the 48 entry — the one size
 *     Google actually documents — behind a claim that the file didn't have it.
 *   - 48/96/192 are the multiples of 48 Google asks for. favicon-48x48.png was being
 *     generated and then referenced by nothing, so the smallest compliant PNG on disk
 *     was never offered. It is listed now.
 * Keep this ascending by size, and keep it honest: if gen-favicon.js's output sizes
 * change, these attributes change with them (scripts/invariants.test.js pins that).
 */
