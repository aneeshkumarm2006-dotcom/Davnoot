/**
 * The hreflang cluster for a page that exists in both languages.
 *
 * Emitted on BOTH sides and pointing at BOTH URLs including itself — that
 * reciprocity is not optional. Google ignores a one-way annotation entirely, and
 * an unannotated pair of near-identical pages is exactly what it treats as
 * duplicate content, which is the failure mode this whole feature exists to avoid.
 *
 * LANGUAGE GRANULARITY IS DELIBERATELY ASYMMETRIC:
 *   en      — not en-CA. The Organization schema says areaServed "Worldwide"; the
 *             English pages rank for US and global queries today, and pinning them
 *             to Canada would tell Google to prefer them only for Canadian users.
 *   fr-CA   — the French pages ARE for Quebec. Quebec French is not France French
 *             (the copy says "courriel" and "magasinage"), so claiming plain "fr"
 *             would invite Google to serve them to France, where they read oddly.
 *   x-default — English, the entry point for anyone we have no better match for.
 */
export function hreflangTags(file) {
  if (!TRANSLATED_PAGES.has(file)) return [];
  const en = canonicalFor(file, 'en');
  const fr = canonicalFor(file, 'fr');
  return [
    `<link rel="alternate" hreflang="en" href="${en}" />`,
    `<link rel="alternate" hreflang="fr-CA" href="${fr}" />`,
    `<link rel="alternate" hreflang="x-default" href="${en}" />`,
  ];
}

export function seoHtml(file, title, desc, faqs, locale = DEFAULT_LOCALE) {
  const canonical = canonicalFor(file, locale);
  // A French page canonicalises to ITSELF. Pointing it at the English URL — the
  // reflex when you think of French as "a version of" the real page — would ask
  // Google to drop it from the index, and no amount of hreflang would bring it back.
  const kw = locale === 'fr' ? KEYWORDS_FR[file] : KEYWORDS[file];
  /* A French page whose dictionary is not finished is still ROUTED — so it can be
   * reviewed in a browser before it goes live — but it must not be indexable. It
   * is mostly the English page at that point, and letting Google have it competes
   * with the English original for the same terms. `follow` so its links still
   * pass authority; the page leaves noindex by itself the moment its translation
   * completes and TRANSLATED_PAGES picks it up. */
  const indexable = locale !== 'fr' || TRANSLATED_PAGES.has(file);
  return [
    `<link rel="canonical" href="${canonical}" />`,
    `<meta name="robots" content="${indexable ? 'index, follow' : 'noindex, follow'}" />`,
    ...(kw && kw.length ? [`<meta name="keywords" content="${esc(kw.join(', '))}" />`] : []),
    ...hreflangTags(file),
    ...FAVICON_TAGS,
    `<meta property="og:type" content="website" />`,
    `<meta property="og:site_name" content="Davnoot" />`,
    `<meta property="og:title" content="${esc(title)}" />`,
    `<meta property="og:description" content="${esc(desc)}" />`,
    `<meta property="og:url" content="${canonical}" />`,
    `<meta property="og:image" content="${OG_IMAGE}" />`,
    // og:locale rides WITH its alternate, on the bilingual pages only. Emitting it
    // on the 37 English-only pages too would be defensible, but it would rewrite
    // every page on the site — and every one of those bytes would have to be
    // re-frozen and re-reviewed for a tag that tells a crawler nothing it cannot
    // already see from `lang`. Scope stays on the pages this feature is about.
    ...(TRANSLATED_PAGES.has(file)
      ? [
          `<meta property="og:locale" content="${locale === 'fr' ? 'fr_CA' : 'en_CA'}" />`,
          `<meta property="og:locale:alternate" content="${locale === 'fr' ? 'en_CA' : 'fr_CA'}" />`,
        ]
      : []),
    `<meta name="twitter:card" content="summary_large_image" />`,
    `<meta name="twitter:title" content="${esc(title)}" />`,
    `<meta name="twitter:description" content="${esc(desc)}" />`,
    `<meta name="twitter:image" content="${OG_IMAGE}" />`,
    `<script type="application/ld+json">\n${jsonLd(file, title, desc, faqs, locale)}\n</script>`,
  ].join('\n');
}
